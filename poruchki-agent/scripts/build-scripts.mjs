#!/usr/bin/env node
// Bundle the feedback agent's script (agent/feedback-bg.json + its prompt and style), the „невзета пратка“
// script (agent/pickup-bg.json)
// the incoming line's script (Стела, agent/inbound-zdravets.json – the catalogue is
// filled in at call time from agent/pricelist-zdravets.json) and the hard situations of the
// order-confirmation calls (agent/order-situations-bg.md, added to the ElevenLabs agent's script)
// into lib/scripts.generated.mjs,
// so calls use the text from git – no copying into the ElevenLabs dashboard.
//   node scripts/build-scripts.mjs          (re-run after editing the agent/ files)
//   node scripts/build-scripts.mjs --check  (fails if the generated file is out of date)
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import { loadSpec } from "../lib/prompt.mjs";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(root, "lib/scripts.generated.mjs");

export async function buildScripts() {
  const { spec, prompt } = await loadSpec(join(root, "agent/feedback-bg.json"));
  const dataCollection = Object.fromEntries(
    Object.entries(spec.data_collection).map(([id, d]) => [id, typeof d === "string" ? { type: "string", description: d } : d]),
  );
  const feedback = { prompt, firstMessage: spec.first_message, language: spec.language || "bg", dataCollection };
  const pk = await loadSpec(join(root, "agent/pickup-bg.json"));
  const pickup = {
    prompt: pk.prompt,
    firstMessage: pk.spec.first_message,
    language: pk.spec.language || "bg",
    dataCollection: Object.fromEntries(Object.entries(pk.spec.data_collection).map(([id, d]) => [id, typeof d === "string" ? { type: "string", description: d } : d])),
  };
  const inb = await loadSpec(join(root, "agent/inbound-zdravets.json"), { keepPriceList: true });
  const inbound = { prompt: inb.prompt, firstMessage: inb.spec.first_message, language: inb.spec.language || "bg" };
  const situations = (await readFile(join(root, "agent/order-situations-bg.md"), "utf8")).trim();
  return [
    "// Generated by scripts/build-scripts.mjs from agent/feedback-bg.json, agent/pickup-bg.json, agent/inbound-zdravets.json and agent/order-situations-bg.md – do not edit by hand.",
    `export const FEEDBACK_SCRIPT = ${JSON.stringify(feedback, null, 2)};`,
    "",
    "// „Невзета пратка“: Елена calls a customer whose parcel waits at the courier's office (lib/pickup-calls.mjs).",
    `export const PICKUP_SCRIPT = ${JSON.stringify(pickup, null, 2)};`,
    "",
    "// The incoming line (Стела): [[PRICE_LIST]] is filled in at call time (offers end by date).",
    `export const INBOUND_SCRIPT = ${JSON.stringify(inbound, null, 2)};`,
    "",
    "// Order-confirmation calls: hard situations, added after the ElevenLabs agent's script (lib/callback.mjs).",
    `export const ORDER_SITUATIONS = ${JSON.stringify(situations)};`,
    "",
  ].join("\n");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const text = await buildScripts();
  if (process.argv.includes("--check")) {
    const current = await readFile(OUT, "utf8").catch(() => "");
    if (current !== text) {
      console.error("lib/scripts.generated.mjs is out of date – run node scripts/build-scripts.mjs");
      process.exit(1);
    }
    console.log("up to date");
  } else {
    await writeFile(OUT, text);
    console.log(`wrote ${OUT}`);
  }
}
