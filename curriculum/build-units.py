import json, re, os

TR = dict(zip("абвгдежзийклмнопрстуфхцчшщъьюя", ["a","b","v","g","d","e","zh","z","i","y","k","l","m","n","o","p","r","s","t","u","f","h","ts","ch","sh","sht","a","y","yu","ya"]))
def slug(prefix, s):
    s = "".join(TR.get(c, c) for c in s.lower())
    return prefix + "-" + re.sub(r"[^a-z0-9]+", "-", s).strip("-")[:48]

units = []
def add(grade, section, grp, title, subtitle="", works=None, topics=None, planned=None, info=None):
    units.append({
        "slug": slug(f"g{grade}", title), "grade": grade, "section": section, "grp": grp, "title": title, "subtitle": subtitle,
        "position": len([u for u in units if u["grade"] == grade]) + 1,
        "match": {"works": works or ([title] if section == "literature" else []), "topics": topics or []},
        "planned": list(planned or []), "info": info or ({"textbook": True} if planned is PROT else {}),
    })

